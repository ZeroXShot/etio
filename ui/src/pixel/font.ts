/** The rows of a character's glyph ("#" set, "." clear). */
export function glyph(c: string): readonly string[] {
  return GLYPHS[c.toUpperCase()] ?? GLYPHS[" "]!;
}

/** Renders `s` in palette key `key` with `spacing` pixels between glyphs. */
export function text(s: string, key = "f", spacing = 1): Sprite {
  const glyphs = [...s].map((c) => parse(glyph(c).map((row) => row.replaceAll("#", key))));
  return hstack(glyphs, spacing);
}
